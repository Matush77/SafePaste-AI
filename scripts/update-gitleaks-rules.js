// Generates src/detection/data/gitleaksRules.js from a pinned gitleaks
// release (MIT licence). Run after changing GITLEAKS_VERSION:
//
//   node scripts/update-gitleaks-rules.js
//
// gitleaks rules are written for Go's RE2 engine; goRegex.js converts them
// to JavaScript.
// Rules that only match file paths are dropped.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";
import { convertRegex } from "./goRegex.js";

const GITLEAKS_VERSION = "v8.30.1";
const SOURCE = `https://raw.githubusercontent.com/gitleaks/gitleaks/${GITLEAKS_VERSION}/config/gitleaks.toml`;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src", "detection", "data", "gitleaksRules.js");

const config = /** @type {any} */ (parse(await (await fetch(SOURCE)).text()));

const rules = [];
const skipped = [];
for (const rule of config.rules) {
  if (!rule.regex) {
    skipped.push(`${rule.id} (path rule)`);
    continue;
  }
  try {
    const converted = convertRegex(rule.regex);
    new RegExp(converted.source, `${converted.flags}g`);
    rules.push({
      id: rule.id,
      regex: converted.source,
      flags: converted.flags,
      keywords: (rule.keywords || []).map((/** @type {string} */ keyword) => keyword.toLowerCase()),
      secretGroup: rule.secretGroup ?? null,
      entropy: rule.entropy ?? null,
      allowlists: (rule.allowlists || [])
        // Path conditions never apply to pasted text.
        .filter((/** @type {any} */ list) => !(list.paths && list.condition === "AND") && (list.regexes || list.stopwords))
        .map((/** @type {any} */ list) => ({
          target: list.regexTarget || "secret",
          regexes: (list.regexes || []).map(convertRegex),
          stopwords: (list.stopwords || []).map((/** @type {string} */ word) => word.toLowerCase())
        }))
    });
  } catch (error) {
    skipped.push(`${rule.id} (${/** @type {Error} */ (error).message})`);
  }
}

const globalAllowlist = {
  regexes: (config.allowlist.regexes || []).map(convertRegex),
  stopwords: (config.allowlist.stopwords || []).map((/** @type {string} */ word) => word.toLowerCase())
};

const header = `// GENERATED by scripts/update-gitleaks-rules.js from gitleaks ${GITLEAKS_VERSION}.
// Do not edit by hand; change the script and re-run it.
//
// Rules from gitleaks (https://github.com/gitleaks/gitleaks), MIT License,
// Copyright (c) 2019 Zachary Rice. See THIRD_PARTY_NOTICES.md.
`;
writeFileSync(output, `${header}
export const GITLEAKS_VERSION = ${JSON.stringify(GITLEAKS_VERSION)};

/** @type {import("../gitleaks.js").GitleaksRule[]} */
export const GITLEAKS_RULES = ${JSON.stringify(rules, null, 1)};

/** @type {import("../gitleaks.js").GitleaksAllowlist} */
export const GITLEAKS_GLOBAL_ALLOWLIST = ${JSON.stringify(globalAllowlist, null, 1)};
`);
console.log(`Wrote ${rules.length} rules to ${output}`);
if (skipped.length) {
  console.log(`Skipped ${skipped.length}:\n  ${skipped.join("\n  ")}`);
}

