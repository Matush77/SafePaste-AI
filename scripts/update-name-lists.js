// Generates src/detection/data/names.js from public-domain name data:
//
//   node scripts/update-name-lists.js
//
// - First names: US Social Security Administration baby names, 1880-2008
//   (the top 1000 per year), via hadley/data-baby-names.
// - Surnames: US Census Bureau 2010 surnames, via fivethirtyeight/data.
// - Name words: names that are also ordinary English words ("will", "grace",
//   "king"), from the public-domain ENABLE word list. Rules treat these more
//   carefully, since "Grace Period" or "Rose Garden" are not people.
// The official sites block automated downloads, so pinned mirrors are used.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCES = {
  firstNames: "https://raw.githubusercontent.com/hadley/data-baby-names/b6525579cf7d2816e77fa885299445d15a09c906/baby-names.csv",
  surnames: "https://raw.githubusercontent.com/fivethirtyeight/data/4c1ff5e3aef1816ae04af63218015066e186c147/most-common-name/surnames.csv",
  words: "https://raw.githubusercontent.com/dolph/dictionary/c65f04b0b5b27a981f437b940cf62fe71320d5ec/enable1.txt"
};
// First names whose share of births, summed over the years, is at least this.
const FIRST_NAME_MIN_SHARE = 0.0005;
// The most common surnames kept.
const SURNAME_COUNT = Number(process.env.SURNAME_COUNT || 20000);

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src", "detection", "data", "names.js");

const [babyNames, surnameCsv, wordList] = await Promise.all(Object.values(SOURCES).map(async (url) => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${response.status} for ${url}`);
  }
  return response.text();
}));

/** @type {Map<string, number>} */
const share = new Map();
for (const line of babyNames.split("\n").slice(1)) {
  const match = /^\d{4},"([A-Za-z]+)",([\d.e-]+),/.exec(line);
  if (match) {
    const name = match[1].toLowerCase();
    share.set(name, (share.get(name) || 0) + Number(match[2]));
  }
}
const firstNames = [...share].filter(([name, total]) => total >= FIRST_NAME_MIN_SHARE && name.length >= 2).sort((a, b) => b[1] - a[1]).map(([name]) => name);

const surnames = surnameCsv
  .split("\n")
  .slice(1)
  .map((line) => line.split(",")[0].toLowerCase())
  .filter((name) => /^[a-z]{2,}$/.test(name))
  .slice(0, SURNAME_COUNT);

const words = new Set(wordList.split(/\r?\n/));
const nameWords = [...new Set([...firstNames, ...surnames])].filter((name) => words.has(name)).sort();

const list = (/** @type {string[]} */ names) => names.join(" ").replace(/(.{1,118})(?: |$)/g, "$1\n").trim();
writeFileSync(output, `// GENERATED by scripts/update-name-lists.js. Do not edit by hand.
//
// First names: US Social Security Administration baby names 1880-2008
// (public domain), via github.com/hadley/data-baby-names.
// Surnames: US Census Bureau 2010 surnames (public domain), via
// github.com/fivethirtyeight/data (CC BY 4.0). See THIRD_PARTY_NOTICES.md.
// Name words: names that are also words in the public-domain ENABLE list.

const split = (/** @type {string} */ list) => new Set(list.split(/\\s+/).filter(Boolean));

/** ${firstNames.length} first names, most common first. */
export const COMMON_FIRST_NAMES = split(\`
${list(firstNames)}
\`);

/** The ${surnames.length} most common surnames. */
export const SURNAMES = split(\`
${list(surnames)}
\`);

/** ${nameWords.length} names that are also ordinary English words. */
export const NAME_WORDS = split(\`
${list(nameWords)}
\`);
`);
console.log(`Wrote ${firstNames.length} first names, ${surnames.length} surnames, ${nameWords.length} name words to ${output}`);
